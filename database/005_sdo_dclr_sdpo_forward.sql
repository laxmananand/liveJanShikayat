/* ---------- Step 1: office kinds and roles ---------- */
BEGIN TRY
    BEGIN TRANSACTION;

    -- Office_Id must mean the same thing everywhere: stop if 6 / 7 / 8 are already used for something else
    IF EXISTS (SELECT 1 FROM dbo.Mst_Regional_Office o
               JOIN (VALUES (6, 'SDO'), (7, 'DCLR'), (8, 'SDPO')) v (Office_Id, Unique_Code) ON v.Office_Id = o.Office_Id
               WHERE o.Unique_Code <> v.Unique_Code)
        THROW 50001, 'Mst_Regional_Office.Office_Id 6, 7 or 8 is already used by another office kind.', 1;

    -- Is_Active = 0: these offices are reached only through a DM / SP, never picked by Admin's forward popup
    INSERT INTO dbo.Mst_Regional_Office (Office_Id, Category_Id, Regional_Office, Unique_Code, Is_Active)
    SELECT v.Office_Id, 2, v.Name, v.Unique_Code, 0
    FROM (VALUES (6, N'Sub Divisional Officer', 'SDO'),
                 (7, N'Deputy Collector Land Reforms', 'DCLR'),
                 (8, N'Sub Divisional Police Officer', 'SDPO')) v (Office_Id, Name, Unique_Code)
    WHERE NOT EXISTS (SELECT 1 FROM dbo.Mst_Regional_Office o WHERE o.Office_Id = v.Office_Id);

    -- The role name is what the JWT carries and the frontend maps; the Id is whatever the identity gives
    INSERT INTO dbo.Mst_Role (Role, RoleDesc)
    SELECT v.Role, v.RoleDesc
    FROM (VALUES ('SDO', 'Sub Divisional Officer'),
                 ('DCLR', 'Deputy Collector Land Reforms'),
                 ('SDPO', 'Sub Divisional Police Officer / DSP')) v (Role, RoleDesc)
    WHERE NOT EXISTS (SELECT 1 FROM dbo.Mst_Role r WHERE r.Role = v.Role);

    COMMIT TRANSACTION;
    PRINT 'Step 1 done: office kinds 6 (SDO), 7 (DCLR), 8 (SDPO) and their roles.';
END TRY
